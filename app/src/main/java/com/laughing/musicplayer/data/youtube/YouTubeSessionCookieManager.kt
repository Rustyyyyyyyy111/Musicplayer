package com.laughing.musicplayer.data.youtube

import android.content.Context
import android.webkit.CookieManager
import com.laughing.musicplayer.core.util.ActivityLogger
import com.laughing.musicplayer.core.util.SecureCredentialStore
import com.laughing.musicplayer.data.local.SettingsDataStore
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.util.Locale

class YouTubeSessionCookieManager(
    private val context: Context,
    private val credentialStore: SecureCredentialStore,
    private val settingsDataStore: SettingsDataStore,
    private val logger: ActivityLogger
) {
    @Volatile
    private var cachedCookieHeader: String? = null

    private fun ensureLoaded(): String {
        cachedCookieHeader?.let { return it }
        return synchronized(this) {
            cachedCookieHeader ?: credentialStore.getSecret(KEY_COOKIE_HEADER).also {
                cachedCookieHeader = it
            }
        }
    }

    suspend fun warmUp() = withContext(Dispatchers.IO) {
        ensureLoaded()
    }

    fun getCookiesTxtFile(): File = File(context.filesDir, COOKIES_FILE_NAME)

    fun hasActiveCookies(): Boolean = isAuthenticatedCookieHeader(ensureLoaded())

    fun getCookieHeaderForUrl(url: String): String? {
        val header = ensureLoaded()
        if (header.isBlank()) return null
        val host = runCatching { java.net.URI(url).host?.lowercase(Locale.US) }.getOrNull().orEmpty()
        val isYouTubeOrGoogle = host.endsWith("youtube.com") ||
            host.endsWith("youtu.be") ||
            host.endsWith("googlevideo.com") ||
            host.endsWith("youtubei.googleapis.com") ||
            host.endsWith("google.com")
        return if (isYouTubeOrGoogle) header else null
    }

    suspend fun captureCookiesFromWebView(cookieManager: CookieManager): Boolean = withContext(Dispatchers.IO) {
        val musicCookies = runCatching { cookieManager.getCookie("https://music.youtube.com") }.getOrNull().orEmpty()
        val ytCookies = runCatching { cookieManager.getCookie("https://www.youtube.com") }.getOrNull().orEmpty()
        val googleCookies = runCatching { cookieManager.getCookie("https://accounts.google.com") }.getOrNull().orEmpty()

        val mergedMap = parseAndMergeCookies(googleCookies, ytCookies, musicCookies)
        val mergedHeader = mergedMap.entries.joinToString("; ") { "${it.key}=${it.value}" }

        if (!isAuthenticatedCookieHeader(mergedHeader)) {
            return@withContext false
        }

        runCatching { cookieManager.flush() }
        persistCookiesInternal(mergedMap, mergedHeader)
        true
    }

    suspend fun saveRawCookieHeaderForTesting(rawHeader: String): Boolean = withContext(Dispatchers.IO) {
        val parsed = parseAndMergeCookies(rawHeader)
        val normalized = parsed.entries.joinToString("; ") { "${it.key}=${it.value}" }
        if (!isAuthenticatedCookieHeader(normalized)) return@withContext false
        persistCookiesInternal(parsed, normalized)
        true
    }

    private suspend fun persistCookiesInternal(cookieMap: Map<String, String>, header: String) {
        cachedCookieHeader = header
        credentialStore.putSecret(KEY_COOKIE_HEADER, header)
        writeNetscapeCookiesFile(cookieMap)
        settingsDataStore.setYouTubeLoggedIn(true)
        logger.log("YT_AUTH", "INFO", "Đã lưu phiên đăng nhập YouTube Music (${cookieMap.size} cookies) & xuất cookies.txt")
    }

    suspend fun clearSession() = withContext(Dispatchers.IO) {
        cachedCookieHeader = ""
        credentialStore.clearSecret(KEY_COOKIE_HEADER)
        runCatching { getCookiesTxtFile().delete() }
        withContext(Dispatchers.Main) {
            runCatching {
                val cm = CookieManager.getInstance()
                cm.removeAllCookies(null)
                cm.flush()
            }
        }
        settingsDataStore.setYouTubeLoggedIn(false)
        logger.log("YT_AUTH", "INFO", "Đã đăng xuất YouTube Music và xóa cookies.txt")
    }

    private fun writeNetscapeCookiesFile(cookieMap: Map<String, String>) {
        val expiryEpoch = (System.currentTimeMillis() / 1000L) + (365L * 24L * 60L * 60L)
        val sb = StringBuilder()
        sb.append("# Netscape HTTP Cookie File\n")
        sb.append("# Generated by Music Player\n\n")
        cookieMap.forEach { (name, value) ->
            val secureFlag = if (name.startsWith("__Secure-") || name.startsWith("__Host-") || name == "SAPISID") {
                "TRUE"
            } else {
                "FALSE"
            }
            listOf(".youtube.com", ".music.youtube.com").forEach { domain ->
                sb.append(domain).append('\t')
                    .append("TRUE").append('\t')
                    .append("/").append('\t')
                    .append(secureFlag).append('\t')
                    .append(expiryEpoch).append('\t')
                    .append(name).append('\t')
                    .append(value).append('\n')
            }
        }
        getCookiesTxtFile().writeText(sb.toString(), Charsets.UTF_8)
    }

    companion object {
        private const val KEY_COOKIE_HEADER = "youtube_cookie_header"
        private const val COOKIES_FILE_NAME = "cookies.txt"

        const val DEFAULT_USER_AGENT =
            "Mozilla/5.0 (Linux; Android 14; Pixel 8 Pro) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0.0.0 Mobile Safari/537.36"

        private val AUTH_COOKIE_NAMES = setOf(
            "SAPISID",
            "__Secure-3PAPISID",
            "__Secure-1PAPISID",
            "SID",
            "__Secure-3PSID",
            "__Secure-1PSID"
        )

        fun parseAndMergeCookies(vararg rawHeaders: String): Map<String, String> {
            val map = linkedMapOf<String, String>()
            rawHeaders.forEach { raw ->
                raw.split(";").forEach { part ->
                    val idx = part.indexOf('=')
                    if (idx > 0) {
                        val key = part.substring(0, idx).trim()
                        val value = part.substring(idx + 1).trim()
                        if (key.isNotEmpty() && value.isNotEmpty()) {
                            map[key] = value
                        }
                    }
                }
            }
            return map
        }

        fun isAuthenticatedCookieHeader(header: String?): Boolean {
            if (header.isNullOrBlank()) return false
            val parsed = parseAndMergeCookies(header)
            return AUTH_COOKIE_NAMES.any { parsed.containsKey(it) }
        }
    }
}
